#!/usr/bin/env node

// book-kit conventions
//
// Print the book's writing conventions as Markdown, from its resolved config:
// the callouts and how to write them, the structure the validators expect,
// which checks run, and each preset's CONVENTIONS.md. The Claude agents in
// claude-plugin/ read this instead of hardcoding one house style.

import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadConfig } from '../lib/config.js';
import { enabledRules } from '../lib/lint.js';
import { BUILTIN_VALIDATORS } from '../validators/index.js';

const config = loadConfig();
const { callouts = [], structure, validators, paths } = config;
const code = (s) => `\`${s}\``;
const lines = [];
const say = (...more) => lines.push(...more);

say(
  `# Writing conventions: ${config.metadata.title}`,
  '',
  `Generated by ${code('book-kit conventions')} from book.config.yml${config.presets.length ? ` and ${config.presets.map((p) => code(p.name)).join(', ')}` : ''}. The book's CLAUDE.md and style guide win where they differ.`,
  '',
  '## Structure',
  '',
  `- Chapters are Markdown files in ${code(`${paths.src}/`)}, built in the order ${code(paths.index)} lists them. Add a new chapter to ${code(paths.index)} in the same change.`,
  '- Each chapter opens with an H2 title. Use H3 and H4 below it, and never skip a level.',
);
if (structure.required_callout) {
  say(`- Every chapter opens with a ${code(`.${structure.required_callout}`)} callout, right after the title.`);
}
if (callouts.some((c) => c.class === 'takeaways')) {
  say(`- Files ending in ${code(`${structure.takeaways_suffix}.md`)} are generated from the TL;DRs by ${code('just key-takeaways')}; never edit them by hand.`);
}
say(
  `- Not narrative chapters (skipped by the prose checks): ${structure.structural_slugs.map(code).join(', ')}, and drafts ending in ${code(`${structure.draft_suffix}.md`)}.`,
  '',
  '## Callouts',
  '',
  callouts.length
    ? 'Write a callout as a fenced div whose class and custom-style match. The build adds the label, so never type it; a typed one renders twice.'
    : 'This book defines no callouts.',
  '',
);
if (callouts.length) {
  const first = callouts[0].class;
  say('```markdown', `::: {.${first} custom-style="${first}"}`, 'Text.', ':::', '```', '');
  for (const c of callouts) {
    const label = c.label ? ` (label "${c.label}")` : '';
    const pair = c.pair_with ? `; a chapter with one should also have ${code(`.${c.pair_with}`)}` : '';
    say(`- ${code(`.${c.class}`)}${label}${c.aria ? `: ${c.aria}` : ''}${pair}`);
  }
  say('');
}

const on = BUILTIN_VALIDATORS.map((v) => v.name).filter((name) => validators.severity?.[name] !== 'off');
const rules = enabledRules(config).map((r) => r.name);
say(
  '## Checks',
  '',
  `Run ${code('just check-all')} before handing work back: ${code('book-kit validate')}, markdownlint, and textlint.`,
  '',
  `- Validators that run: ${on.map(code).join(', ')}.${(validators.plugins ?? []).length ? ` Plus the book's own: ${validators.plugins.map(code).join(', ')}.` : ''}`,
  `- The kit's prose rules that run: ${rules.length ? rules.map(code).join(', ') : 'none'}.`,
  '',
);

for (const { name, dir } of config.presets) {
  const file = join(dir, 'CONVENTIONS.md');
  if (existsSync(file)) say(`<!-- from preset ${name} -->`, '', readFileSync(file, 'utf8').trim(), '');
}

process.stdout.write(`${lines.join('\n').trimEnd()}\n`);
