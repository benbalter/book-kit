// Resolved lint configs for a book: the kit's base configs, layered with the
// presets' and the book's settings, the same way book.config.yml is.
//
//   textlint      configs/textlintrc.json, deep-merged with lint.textlint
//   kit rules     rules/*.js and each preset's rules/*.js, switched on and
//                 configured by lint.rules (name -> true | false | options)
//   markdownlint  configs/markdownlint-cli2.jsonc's `config`, deep-merged
//                 with lint.markdownlint
//
// textlint gives rules loaded with --rulesdir no config at all (they can't
// be switched off or given options), and only rules named by package or path
// in a textlintrc get options. So the build writes one rules directory per
// book holding a small wrapper for each enabled rule, named like the rule and
// with its options baked in, and points --rulesdir at that.
//
// A book with its own .textlintrc or .markdownlint-cli2.jsonc uses that file
// as is (and, for textlint, every kit rule), as before presets existed.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { deepMerge, kitPath, pathFor } from './config.js';

const BOOK_TEXTLINTRC = '.textlintrc';
const BOOK_MARKDOWNLINT = '.markdownlint-cli2.jsonc';

const ruleFiles = (dir) =>
  existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.js')).sort().map((f) => join(dir, f)) : [];

const ruleName = (file) => basename(file, '.js');

// Our own JSONC files only use whole-line // comments.
function readJsonc(file) {
  return JSON.parse(readFileSync(file, 'utf8').replace(/^\s*\/\/.*$/gm, ''));
}

/**
 * The textlint rules a book enables, in name order: [{ name, file, options }].
 * Kit rules are on only when lint.rules turns them on; a preset's rules are
 * on unless lint.rules turns them off.
 * @param {object} config - Resolved config
 */
export function enabledRules(config) {
  const settings = config.lint?.rules ?? {};
  const candidates = [
    ...ruleFiles(kitPath('rules')).map((file) => ({ file, on: Boolean(settings[ruleName(file)]) })),
    ...(config.presets ?? []).flatMap(({ dir }) =>
      ruleFiles(join(dir, 'rules')).map((file) => ({ file, on: settings[ruleName(file)] !== false })),
    ),
  ];
  const byName = new Map();
  for (const { file, on } of candidates) byName.set(ruleName(file), { file, on }); // later layers win
  return [...byName.entries()]
    .filter(([, { on }]) => on)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([name, { file }]) => {
      const setting = settings[name];
      const options = setting && typeof setting === 'object' ? setting : {};
      return { name, file, options };
    });
}

/**
 * Whether command-line arguments for textlint or markdownlint name what to
 * lint. Options and their values pass through untouched, so a value like
 * `--format json` or a formatter's .js path isn't taken for a file: an
 * argument names files only when it ends in .md, is a glob, or is a directory.
 * @param {string[]} args
 * @param {string} cwd - Where relative paths resolve (the book root)
 */
export function namesFiles(args, cwd) {
  return args.some((arg) => {
    if (arg.startsWith('-')) return false;
    if (arg.endsWith('.md') || arg.includes('*')) return true;
    try {
      return statSync(join(cwd, arg)).isDirectory();
    } catch {
      return false;
    }
  });
}

/** The textlintrc a book gets: the kit base merged with lint.textlint. */
export function textlintConfig(config) {
  return deepMerge(readJsonc(kitPath('configs', 'textlintrc.json')), config.lint?.textlint ?? {});
}

/** The markdownlint-cli2 config a book gets: the kit base merged with lint.markdownlint. */
// Drafts (structure.draft_suffix) aren't linted.
export function markdownlintConfig(config) {
  const base = readJsonc(kitPath('configs', 'markdownlint-cli2.jsonc'));
  const drafts = `**/*${config.structure?.draft_suffix ?? '-scratch'}.md`;
  return {
    ...base,
    config: deepMerge(base.config, config.lint?.markdownlint ?? {}),
    ignores: [drafts, ...(base.ignores ?? [])],
  };
}

function wrapperSource({ name, file, options }) {
  return `// Generated by book-kit for the book's textlint run (lib/lint.js): the
// ${name} rule with its lint.rules options. Edit book.config.yml, not this file.
import rule from ${JSON.stringify(file)};

const options = ${JSON.stringify(options)};
const withOptions = (reporter) => reporter && ((context, own = {}) => reporter(context, { ...options, ...own }));

export default typeof rule === 'function'
  ? withOptions(rule)
  : { ...rule, linter: withOptions(rule.linter), fixer: withOptions(rule.fixer) };
`;
}

/**
 * Write the book's textlint config and rules directory under
 * dist/.book-kit/textlint/, or point at the book's own .textlintrc.
 * @param {object} config - Resolved config
 * @returns {{ config: string, rulesdir: string }} paths for --config and --rulesdir
 */
export function prepareTextlint(config) {
  const own = join(config.root, BOOK_TEXTLINTRC);
  if (existsSync(own)) return { config: own, rulesdir: kitPath('rules') };

  const dir = join(pathFor('dist', config), '.book-kit', 'textlint');
  const rulesdir = join(dir, 'rules');
  rmSync(rulesdir, { recursive: true, force: true }); // drop rules the book has since turned off
  mkdirSync(rulesdir, { recursive: true });
  // The wrappers are ES modules, whatever the book's own package.json says.
  writeFileSync(join(dir, 'package.json'), '{ "type": "module" }\n');
  for (const rule of enabledRules(config)) writeFileSync(join(rulesdir, `${rule.name}.js`), wrapperSource(rule));
  const out = join(dir, 'textlintrc.json');
  writeFileSync(out, `${JSON.stringify(textlintConfig(config), null, 2)}\n`);
  return { config: out, rulesdir };
}

/**
 * Write the book's markdownlint-cli2 config, or point at the book's own.
 * @param {object} config - Resolved config
 * @returns {string} path for markdownlint-cli2 --config
 */
export function prepareMarkdownlint(config) {
  const own = join(config.root, BOOK_MARKDOWNLINT);
  if (existsSync(own)) return own;
  const dir = join(pathFor('dist', config), '.book-kit');
  mkdirSync(dir, { recursive: true });
  const out = join(dir, 'markdownlint-cli2.jsonc');
  writeFileSync(out, `${JSON.stringify(markdownlintConfig(config), null, 2)}\n`);
  return out;
}
